import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const ExcelJS = createRequire(import.meta.url)("exceljs");

test("border controls match the reference, shared edges undo, clear, merge and round-trip through Excel", async ({ page, browser }) => {
  const context = await browser.newContext(), peer = await context.newPage(), stamp = Date.now(), errors = [];
  for (const p of [page, peer]) p.on("pageerror", (e) => errors.push(e.message));
  try {
    for (const [client, name] of [[page.request, "owner"], [context.request, "viewer"]])
      expect((await client.post("/api/auth/register", { data: { name, email: `border-${name}-${stamp}@example.com`, password: "BorderPass1234" } })).ok()).toBeTruthy();
    const doc = await (await page.request.post("/api/documents", { data: {} })).json();
    await page.request.put(`/api/documents/${doc.id}/members`, { data: { email: `border-viewer-${stamp}@example.com`, role: "viewer" } });
    await page.goto(`/?doc=${doc.id}`); await peer.goto(`/?doc=${doc.id}`);
    const select = async (range) => { await page.getByLabel("Диапазон", { exact: true }).fill(range); await page.getByLabel("Диапазон", { exact: true }).press("Enter"); };
    const edge = (p, key, side) => p.locator(`[data-cell="${key}"] [data-border="${side}"]`);
    const open = async () => { await page.getByRole("button", { name: "Границы ячеек", exact: true }).click(); };
    await select("B2:C3"); await open();
    const panel = page.getByRole("menu", { name: "Границы ячеек", exact: true }), box = await panel.boundingBox();
    expect(box.width).toBe(230); expect(box.height).toBe(90); expect(box.x).toBe(817); expect(box.y).toBe(100);
    await expect(panel.getByRole("menuitem")).toHaveCount(10);
    await page.screenshot({ path: "artifacts/borders-panel-app.png" });
    await panel.getByRole("button", { name: "Стиль границ", exact: true }).click();
    const styles = page.getByRole("menu", { name: "Стиль границ", exact: true }), styleBox = await styles.boundingBox();
    expect(styleBox.width).toBe(122); expect(styleBox.height).toBe(158); expect(styleBox.x).toBe(1006); expect(styleBox.y).toBe(171);
    await page.screenshot({ path: "artifacts/border-styles-app.png" });
    await styles.getByRole("menuitemradio", { name: "Толстая граница", exact: true }).click();
    await panel.getByRole("button", { name: "Цвет границы", exact: true }).click();
    const palette = page.getByRole("dialog", { name: "Цвет границы", exact: true }), paletteBox = await palette.boundingBox();
    expect(paletteBox.width).toBe(244); expect(paletteBox.height).toBe(346); expect(paletteBox.x).toBe(1006); expect(paletteBox.y).toBe(145);
    await page.screenshot({ path: "artifacts/border-colors-app.png" });
    await palette.getByRole("grid", { name: "Цвета границы", exact: true }).getByRole("gridcell", { name: "красный", exact: true }).click();
    await panel.getByRole("menuitem", { name: "Все границы", exact: true }).click();
    await expect(edge(peer, "1,1", "right")).toHaveCSS("border-left-width", "3px");
    await expect(edge(peer, "1,1", "right")).toHaveCSS("border-left-color", "rgb(255, 0, 0)");
    const a = await edge(peer, "1,1", "right").boundingBox(), b = await edge(peer, "1,2", "left").boundingBox();
    expect(a.x).toBe(b.x); expect(a.width).toBe(b.width);
    await page.getByRole("grid").press("Control+z"); await expect(edge(peer, "1,1", "right")).toHaveCount(0);
    await page.getByRole("grid").press("Control+y"); await expect(edge(peer, "1,1", "right")).toHaveCount(1);
    await page.getByRole("button", { name: "Формат", exact: true }).click();
    await page.getByRole("menuitem", { name: "Очистить форматирование", exact: true }).click();
    await expect(edge(peer, "1,1", "top")).toHaveCount(0);
    await expect(edge(peer, "0,1", "bottom")).toHaveCount(0);
    await open(); await panel.getByRole("menuitem", { name: "Внешние границы", exact: true }).click();
    await expect(edge(peer, "1,1", "top")).toHaveCount(1); await expect(edge(peer, "1,1", "right")).toHaveCount(0);
    await select("E5:F6"); await page.getByRole("button", { name: "Объединить ячейки", exact: true }).click();
    await expect(page.locator('[data-cell="4,4"]')).toHaveAttribute("colspan", "2");
    await open(); await panel.getByRole("menuitem", { name: "Все границы", exact: true }).click();
    await expect(edge(peer, "4,4", "right")).toHaveCount(2);
    await expect(edge(peer, "4,4", "bottom")).toHaveCount(2);
    await page.getByRole("grid").evaluate((grid) => {
      window.borderClipboard = new DataTransfer();
      grid.dispatchEvent(new ClipboardEvent("copy", { bubbles: true, clipboardData: window.borderClipboard }));
    });
    await select("H5");
    await page.getByRole("grid").evaluate((grid) => grid.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, clipboardData: window.borderClipboard })));
    await expect(edge(peer, "4,7", "right")).toHaveCount(2);
    const download = page.waitForEvent("download");
    await page.getByRole("button", { name: "Файл", exact: true }).click(); await page.getByRole("button", { name: "Скачать Excel (.xlsx)", exact: true }).click();
    const bytes = await readFile(await (await download).path()), book = new ExcelJS.Workbook(); await book.xlsx.load(bytes);
    expect(book.worksheets[0].getCell("C3").border.bottom.style).toBe("thick");
    expect(book.worksheets[0].getCell("C3").border.bottom.color.argb.toUpperCase()).toBe("FFFF0000");
    await select("A12");
    await page.locator('input[type="file"]').setInputFiles({ name: "borders.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: bytes });
    await expect(edge(peer, "12,1", "top")).toHaveCount(1);
    await expect(edge(peer, "15,4", "right")).toHaveCount(2);
    await page.reload(); await expect(edge(page, "1,1", "top")).toHaveCount(1);
    await open(); await panel.getByRole("button", { name: "Цвет границы", exact: true }).click();
    await palette.getByLabel("Пользовательский цвет границы", { exact: true }).fill("#123456");
    await panel.getByRole("button", { name: "Стиль границ", exact: true }).click();
    await styles.getByRole("menuitemradio", { name: "Двойная граница", exact: true }).click();
    await panel.getByRole("menuitem", { name: "Нижняя граница", exact: true }).click();
    await expect(edge(peer, "0,0", "bottom")).toHaveCSS("border-top-style", "double");
    await expect(edge(peer, "0,0", "bottom")).toHaveCSS("border-top-color", "rgb(18, 52, 86)");
    await open(); await panel.getByRole("button", { name: "Стиль границ", exact: true }).click();
    await panel.getByRole("button", { name: "Стиль границ", exact: true }).press("Escape");
    await expect(styles).toHaveCount(0); await expect(panel).toBeVisible();
    await panel.getByRole("menuitem", { name: "Все границы", exact: true }).focus();
    await page.keyboard.press("End");
    await expect(panel.getByRole("menuitem", { name: "Убрать границы", exact: true })).toBeFocused();
    await page.keyboard.press("Escape"); await expect(panel).toHaveCount(0);
    await expect(page.getByRole("grid")).toBeFocused();
    await page.setViewportSize({ width: 1024, height: 768 });
    await open(); await panel.getByRole("button", { name: "Цвет границы", exact: true }).click();
    const narrow = await palette.boundingBox(); expect(narrow.x).toBeGreaterThanOrEqual(8); expect(narrow.x + narrow.width).toBeLessThanOrEqual(1016);
    await expect(peer.getByRole("button", { name: "Границы ячеек", exact: true })).toHaveCount(0);
    expect(errors).toEqual([]);
  } finally { await context.close(); }
});
