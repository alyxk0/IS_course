import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const ExcelJS = createRequire(import.meta.url)("exceljs");
test("number formats synchronize, custom masks and text input undo correctly, and the menu matches reference geometry", async ({ page, browser }) => {
  const context = await browser.newContext(), viewer = await context.newPage(), stamp = Date.now(), errors = [];
  for (const p of [page, viewer]) p.on("pageerror", (e) => errors.push(e.message));
  try {
    for (const [client, name] of [[page.request, "owner"], [context.request, "viewer"]])
      expect((await client.post("/api/auth/register", { data: { name, email: `numbers-${name}-${stamp}@example.com`, password: "NumbersPass1234" } })).ok()).toBeTruthy();
    const doc = await (await page.request.post("/api/documents", { data: {} })).json();
    await page.request.put(`/api/documents/${doc.id}/members`, { data: { email: `numbers-viewer-${stamp}@example.com`, role: "viewer" } });
    await page.goto(`/?doc=${doc.id}`); await viewer.goto(`/?doc=${doc.id}`);
    const cell = (p, key) => p.locator(`[data-cell="${key}"] .cell-value`);
    const select = async (range) => { await page.getByLabel("Диапазон", { exact: true }).fill(range); await page.getByLabel("Диапазон", { exact: true }).press("Enter"); };
    const input = async (text) => { await page.getByLabel("Строка формул", { exact: true }).fill(text); await page.getByLabel("Строка формул", { exact: true }).press("Enter"); };
    const format = async (name) => { await page.getByLabel("Числовой формат", { exact: true }).click(); await page.getByRole("menuitemcheckbox", { name, exact: true }).click(); };
    await input("=DATE(2026,10,19)+0.5"); await select("A1");
    await format("Дата и время");
    await expect(page.getByRole("grid")).toBeFocused();
    await expect(cell(viewer, "0,0")).toHaveText("19.10.2026 12:00:00");
    await select("B1"); await input("1.5"); await select("B1"); await format("Продолжительность");
    await expect(cell(viewer, "0,1")).toHaveText("36:00:00");
    await select("C1"); await format("Обычный текст"); await input("00123");
    await expect(cell(viewer, "0,2")).toHaveText("00123");
    await select("C1"); await input("=A1");
    await expect(cell(viewer, "0,2")).toHaveText("=A1");
    await page.getByRole("grid").press("Control+z");
    await expect(cell(viewer, "0,2")).toHaveText("00123");
    await page.getByRole("grid").press("Control+y");
    await expect(cell(viewer, "0,2")).toHaveText("=A1");
    await select("D1"); await input("=-1234.5"); await select("D1");
    await page.getByLabel("Числовой формат", { exact: true }).click();
    await page.getByRole("menuitem", { name: "Другие форматы чисел", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Пользовательские числовые форматы", exact: true });
    await dialog.getByLabel("Маска формата", { exact: true }).fill("[");
    await expect(dialog.getByRole("button", { name: "Применить", exact: true })).toBeDisabled();
    await dialog.getByLabel("Маска формата", { exact: true }).fill('#,##0.00;[Red](#,##0.00);"—";@');
    await dialog.getByRole("button", { name: "Применить", exact: true }).click();
    await expect(cell(viewer, "0,3")).toHaveText("(1 234,50)");
    await expect(viewer.locator('[data-cell="0,3"]')).toHaveCSS("color", "rgb(255, 0, 0)");
    await page.getByRole("button", { name: "Увеличить число знаков после запятой", exact: true }).click();
    await expect(cell(viewer, "0,3")).toHaveText("(1 234,500)");
    await page.getByRole("grid").press("Control+z");
    await expect(cell(viewer, "0,3")).toHaveText("(1 234,50)");
    await select("E1"); await input("1000.12"); await select("E1"); await format("Экспоненциальный");
    await expect(cell(viewer, "0,4")).toHaveText("1,00E+03");
    await page.getByLabel("Числовой формат", { exact: true }).click();
    const menu = page.getByRole("menu", { name: "Числовые форматы", exact: true });
    await expect(menu.getByRole("menuitemcheckbox")).toHaveCount(13);
    await expect(menu.getByRole("menuitem")).toHaveCount(3);
    const box = await menu.boundingBox();
    expect(box.x).toBe(402); expect(box.y).toBe(100); expect(box.width).toBeCloseTo(301.890625, 2); expect(box.height).toBe(594);
    await page.screenshot({ path: "artifacts/number-format-menu-app.png" });
    await menu.press("End");
    await expect(page.getByRole("menuitem", { name: "Другие форматы чисел", exact: true })).toBeFocused();
    await menu.press("Escape"); await expect(menu).toHaveCount(0);
    await page.getByLabel("Числовой формат", { exact: true }).click();
    await page.getByRole("menuitem", { name: "Валюта", exact: true }).click();
    const currencies = page.getByRole("dialog", { name: "Валюты", exact: true });
    await currencies.getByLabel("Поиск валюты", { exact: true }).fill("USD");
    await currencies.getByRole("option").click();
    await currencies.getByLabel("Десятичные знаки валюты", { exact: true }).fill("3");
    await currencies.getByRole("button", { name: "Применить", exact: true }).click();
    await expect(cell(viewer, "0,4")).toHaveText("1 000,120 $");
    await select("F1"); await format("Дата"); await input("19.10.2026");
    await expect(cell(viewer, "0,5")).toHaveText("19.10.2026");
    const download = page.waitForEvent("download");
    await page.getByRole("button", { name: "Файл", exact: true }).click();
    await page.getByRole("button", { name: "Скачать Excel (.xlsx)", exact: true }).click();
    const bytes = await readFile(await (await download).path()), book = new ExcelJS.Workbook();
    await book.xlsx.load(bytes);
    expect(book.worksheets[0].getCell("C1").value).toBe("=A1");
    expect(book.worksheets[0].getCell("C1").numFmt).toBe("@");
    expect(book.worksheets[0].getCell("D1").numFmt).toBe('#,##0.00;[Red](#,##0.00);"—";@');
    expect(book.worksheets[0].getCell("E1").numFmt).toBe('#,##0.000 "$"');
    expect(errors).toEqual([]);
  } finally { await context.close(); }
});
