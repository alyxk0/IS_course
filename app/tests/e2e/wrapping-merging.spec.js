import { test, expect } from "@playwright/test";

test("overflow, wrap and clip synchronize; grouped merges preserve anchors and reject stale confirmation", async ({ page, browser }) => {
  const context = await browser.newContext(), peer = await context.newPage(), stamp = Date.now(), errors = [];
  for (const p of [page, peer]) p.on("pageerror", (e) => errors.push(e.message));
  try {
    for (const [client, name] of [[page.request, "owner"], [context.request, "editor"]])
      expect((await client.post("/api/auth/register", { data: { name, email: `wrap-${name}-${stamp}@example.com`, password: "WrappingPass1234" } })).ok()).toBeTruthy();
    const doc = await (await page.request.post("/api/documents", { data: {} })).json();
    await page.request.put(`/api/documents/${doc.id}/members`, { data: { email: `wrap-editor-${stamp}@example.com`, role: "editor" } });
    await page.goto(`/?doc=${doc.id}`); await peer.goto(`/?doc=${doc.id}`);
    const select = async (p, range) => { await p.getByLabel("Диапазон", { exact: true }).fill(range); await p.getByLabel("Диапазон", { exact: true }).press("Enter"); };
    const input = async (p, value) => { await p.getByLabel("Строка формул", { exact: true }).fill(value); await p.getByLabel("Строка формул", { exact: true }).press("Enter"); };
    const cell = (p, key) => p.locator(`[data-cell="${key}"]`),
      value = (p, key) => cell(p, key).locator(".cell-value");
    const mode = async (name) => { await page.getByRole("button", { name: "Перенос текста", exact: true }).click(); await page.getByRole("menuitemradio", { name, exact: true }).click(); };
    await select(page, "A1"); await input(page, "Long text across empty neighbors ".repeat(3));
    await select(page, "C1"); await input(page, "STOP");
    await expect(value(peer, "0,0")).toHaveClass(/overflowing-value/);
    await expect.poll(async () => (await cell(peer, "0,0").boundingBox()).width).toBe(100);
    await expect.poll(async () => (await value(peer, "0,0").boundingBox()).width).toBeCloseTo(199, 0);
    const neighbor = await cell(page, "0,1").boundingBox();
    await page.mouse.click(neighbor.x + 30, neighbor.y + 10);
    await expect(page.getByLabel("Диапазон", { exact: true })).toHaveValue("B1");
    await select(peer, "B1"); await input(peer, "BLOCK");
    await expect(value(page, "0,0")).not.toHaveClass(/overflowing-value/);
    await expect.poll(async () => (await cell(page, "0,0").boundingBox()).width).toBe(100);
    await select(page, "A1"); await mode("Обрезать текст");
    await select(peer, "B1"); await input(peer, "");
    await expect(value(page, "0,0")).not.toHaveClass(/overflowing-value/);
    await select(page, "A1"); await page.getByRole("button", { name: "Перенос текста", exact: true }).click();
    await expect(value(peer, "0,0")).toHaveText("Long text across empty neighbors ".repeat(3));
    const wrapBox = await page.locator(".text-wrap-popover").boundingBox();
    expect(wrapBox.width).toBe(102); expect(wrapBox.height).toBe(46);
    expect(wrapBox.x).toBe(984); expect(wrapBox.y).toBe(100);
    await page.screenshot({ path: "artifacts/text-wrap-menu-app.png" });
    await page.getByRole("menuitemradio", { name: "Переносить по словам", exact: true }).click();
    await expect.poll(async () => (await cell(peer, "0,0").boundingBox()).height).toBeGreaterThan(40);
    await page.getByRole("grid").press("Control+z");
    await expect.poll(async () => (await cell(peer, "0,0").boundingBox()).height).toBe(21);
    await mode("Перекрывать соседние ячейки");
    await expect(value(peer, "0,0")).toHaveClass(/overflowing-value/);
    await select(page, "A5");
    const formula = page.getByLabel("Строка формул", { exact: true });
    await formula.fill("One"); await formula.press("Alt+Enter"); await formula.pressSequentially("Two");
    await formula.press("Alt+Enter"); await formula.pressSequentially("Three"); await formula.press("Enter");
    await select(page, "A5"); await mode("Обрезать текст");
    await expect(value(peer, "4,0")).toHaveText("One\nTwo\nThree");
    await expect.poll(async () => (await cell(peer, "4,0").boundingBox()).height).toBeGreaterThan(40);
    await select(page, "A6"); await page.getByRole("grid").press("F2");
    const editor = page.getByLabel("Редактирование A6", { exact: true });
    await editor.fill("Cell"); await editor.press("Alt+Enter"); await editor.pressSequentially("Line"); await editor.press("Enter");
    await expect(value(peer, "5,0")).toHaveText("Cell\nLine");
    await expect.poll(async () => (await cell(peer, "5,0").boundingBox()).height).toBeGreaterThan(21);
    await select(page, "A10"); await input(page, "Row A");
    await select(page, "B10"); await input(page, "Discard");
    await select(page, "A11"); await input(page, "Row B");
    await select(page, "A10:B11");
    const openMerge = async () => { await page.getByRole("button", { name: "Выбрать тип объединения", exact: true }).click(); };
    await openMerge();
    const mergeBox = await page.getByRole("menu", { name: "Тип объединения", exact: true }).boundingBox();
    expect(mergeBox.width).toBe(262); expect(mergeBox.height).toBe(142); expect(mergeBox.x).toBe(851); expect(mergeBox.y).toBe(100);
    await page.screenshot({ path: "artifacts/merge-menu-app.png" });
    await page.getByRole("menuitem", { name: "Объединить по горизонтали", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Объединить ячейки?", exact: true })).toBeVisible();
    await select(peer, "D20"); await input(peer, "Concurrent edit");
    await expect(value(page, "19,3")).toHaveText("Concurrent edit");
    await select(peer, "A10");
    await page.getByRole("button", { name: "Объединить", exact: true }).click();
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await expect(page.locator(".error-banner")).toContainText("Данные изменились");
    await expect(cell(peer, "9,0")).toHaveAttribute("colspan", "1");
    await expect(value(peer, "9,1")).toHaveText("Discard");
    await openMerge(); await page.getByRole("menuitem", { name: "Объединить по горизонтали", exact: true }).click();
    await page.getByRole("button", { name: "Объединить", exact: true }).click();
    await expect(cell(peer, "9,0")).toHaveAttribute("colspan", "2");
    await expect(cell(peer, "10,0")).toHaveAttribute("colspan", "2");
    await expect(value(peer, "10,0")).toHaveText("Row B");
    await page.getByRole("button", { name: "Отменить объединение", exact: true }).click();
    await expect(cell(peer, "10,0")).toHaveAttribute("colspan", "1");
    await select(page, "B10"); await input(page, "Column B");
    await select(page, "A10:B11"); await openMerge();
    await page.getByRole("menuitem", { name: "Объединить по вертикали", exact: true }).click();
    await page.getByRole("button", { name: "Объединить", exact: true }).click();
    await expect(cell(peer, "9,0")).toHaveAttribute("rowspan", "2");
    await expect(cell(peer, "9,1")).toHaveAttribute("rowspan", "2");
    await expect(value(peer, "9,1")).toHaveText("Column B");
    await page.reload();
    await expect(cell(page, "9,1")).toHaveAttribute("rowspan", "2");
    await page.request.put(`/api/documents/${doc.id}/members`, { data: { email: `wrap-editor-${stamp}@example.com`, role: "viewer" } });
    await expect(peer.getByRole("button", { name: "Выбрать тип объединения", exact: true })).toHaveCount(0);
    expect(errors).toEqual([]);
  } finally { await context.close(); }
});
